package cn.wwl.orimod.assets;

import static org.junit.jupiter.api.Assertions.*;

import java.nio.file.*;
import java.util.Properties;
import org.junit.jupiter.api.Test;

/** R82: players must be able to run any later NeoForge 21.1.x, so the dependency is an open range, never an exact pin. */
class ModMetadataTest {
    private static final Path ROOT = Path.of(System.getProperty("orimod.projectDir", "."));

    private static Properties gradle() throws Exception {
        var p = new Properties();
        try (var in = Files.newInputStream(ROOT.resolve("gradle.properties"))) { p.load(in); }
        return p;
    }

    @Test void neoForgeRangeIsOpenFromTheTestedBuildToNext21Minor() throws Exception {
        var p = gradle();
        String tested = p.getProperty("neo_version"), range = p.getProperty("neo_version_range");
        assertEquals("[" + tested + ",21.2)", range);
        assertTrue(tested.startsWith("21.1."), tested);
        assertEquals("[1.21.1]", p.getProperty("minecraft_version_range"), "Minecraft stays exact until a port is checked");
    }

    @Test void templateUsesTheRangeAndKeepsLockedRenderLibraries() throws Exception {
        String toml = Files.readString(ROOT.resolve("src/main/templates/META-INF/neoforge.mods.toml"));
        assertTrue(toml.contains("versionRange=\"${neo_version_range}\""), "neoforge dependency must use neo_version_range");
        assertFalse(toml.contains("[${neo_version}]"), "exact NeoForge pin is back");
        assertTrue(toml.contains("versionRange=\"[0.1.17]\""), "GemRender stays locked");
        assertTrue(toml.contains("versionRange=\"[1.0.6]\""), "Flywheel stays locked");
    }

    @Test void generatedMetadataIsOpenEnded() throws Exception {
        var generated = ROOT.resolve("build/generated/sources/modMetadata/META-INF/neoforge.mods.toml");
        if (!Files.exists(generated)) return; // generated by processResources before tests in a normal build
        String toml = Files.readString(generated);
        String neo = toml.substring(toml.indexOf("modId=\"neoforge\""));
        neo = neo.substring(0, neo.indexOf("[[", 1) < 0 ? neo.length() : neo.indexOf("[["));
        assertTrue(neo.contains("versionRange=\"[21.1.248,21.2)\""), neo);
    }
}
